#!/usr/bin/env python3
"""
Convert a folder of per-character bitmap glyphs (a pixel font ripped from a
game) into Adafruit GFX font headers, scaled up by whole pixels so the pixel
look stays crisp.

Each glyph is one image named <prefix><code><ext>, where code = ASCII code +
--offset (e.g. res1065.png is 'A' with --offset 1000). Glyph images are
anchored at the top of the cap height: rows 0..baseline-1 sit above the
baseline and any rows below it are descender. A pixel is ink when its palette
index (or grey level, for non-palette images) equals --ink.

Usage:
    python3 glyphs_to_gfx.py sources/pop/raw/glyphs --prefix res --offset 1000 \\
        --name PrinceOfPersia --scales 1 2 3 4 6
    -> ../myfonts/PrinceOfPersia1x7b.h ... PrinceOfPersia6x7b.h, defining
       `PrinceOfPersia1x7b` etc. Only fonts #included in myutils.h use flash.
    python3 glyphs_to_gfx.py sources/pop/raw/glyphs --prefix res --offset 1000 \\
        --name PrinceOfPersiaDigits --scales 4 --only "0123456789:"
    -> a big time font holding only the digits and the colon
"""

import argparse
from pathlib import Path

from PIL import Image

FIRST, LAST = 0x20, 0x7E


def load_glyph(path, ink):
    """Returns (width, height, rows) where rows is a list of lists of bools"""
    im = Image.open(path)
    if im.mode not in ("P", "L", "1"):
        im = im.convert("L")
    px = im.load()
    w, h = im.size
    return w, h, [[px[x, y] == ink for x in range(w)] for y in range(h)]


def trim(rows):
    """Bounding box of the ink: (x0, y0, x1, y1) inclusive, or None if blank"""
    pts = [(x, y) for y, r in enumerate(rows) for x, v in enumerate(r) if v]
    if not pts:
        return None
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def convert(folder, prefix, offset, ext, ink, baseline, spacing, line_gap, name, scale, out_dir, only=None):
    bitmap = bytearray()
    glyphs = []
    descent = 0
    for code in range(FIRST, LAST + 1):
        path = Path(folder) / f"{prefix}{code + offset}{ext}"
        if not path.exists():
            raise SystemExit(f"missing glyph {path} for {chr(code)!r}")
        w, h, rows = load_glyph(path, ink)
        descent = max(descent, h - baseline)
        box = None if only and chr(code) not in only else trim(rows)
        advance = (w + spacing) * scale
        if box is None:
            glyphs.append((len(bitmap), 0, 0, advance, 0, 0, chr(code)))
            continue
        x0, y0, x1, y1 = box
        bits = []
        for y in range(y0, y1 + 1):
            for _ in range(scale):
                for x in range(x0, x1 + 1):
                    bits.extend([rows[y][x]] * scale)
        start = len(bitmap)
        for i in range(0, len(bits), 8):
            byte = 0
            for j, b in enumerate(bits[i:i + 8]):
                if b:
                    byte |= 0x80 >> j
            bitmap.append(byte)
        gw, gh = (x1 - x0 + 1) * scale, (y1 - y0 + 1) * scale
        glyphs.append((start, gw, gh, advance, x0 * scale, (y0 - baseline) * scale, chr(code)))

    y_advance = (baseline + descent + line_gap) * scale
    font = f"{name}{scale}x7b"
    lines = [f"// {font}: generated by watchfaceutils/glyphs_to_gfx.py from {folder}",
             f"// {scale}x scale of a {baseline}px-cap pixel font",
             f"const uint8_t {font}Bitmaps[] PROGMEM = {{"]
    for i in range(0, len(bitmap), 12):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 12]) + ",")
    lines.append("};\n")
    lines.append(f"const GFXglyph {font}Glyphs[] PROGMEM = {{")
    for off, gw, gh, adv, xo, yo, ch in glyphs:
        lines.append(f"  {{ {off:5d}, {gw:3d}, {gh:3d}, {adv:3d}, {xo:4d}, {yo:4d} }},   // 0x{ord(ch):02X} {ch!r}")
    lines.append("};\n")
    lines.append(f"const GFXfont {font} PROGMEM = {{")
    lines.append(f"  (uint8_t  *){font}Bitmaps,")
    lines.append(f"  (GFXglyph *){font}Glyphs,")
    lines.append(f"  0x{FIRST:02X}, 0x{LAST:02X}, {y_advance} }};\n")
    lines.append(f"// Approx. {len(bitmap) + len(glyphs) * 7 + 7} bytes")
    out = Path(out_dir) / f"{font}.h"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(bitmap)} bitmap bytes)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder")
    ap.add_argument("--prefix", default="")
    ap.add_argument("--offset", type=int, default=0, help="file number minus ASCII code")
    ap.add_argument("--ext", default=".png")
    ap.add_argument("--ink", type=int, default=1, help="palette index / grey level that is ink")
    ap.add_argument("--baseline", type=int, default=7, help="rows above the baseline")
    ap.add_argument("--spacing", type=int, default=1, help="blank columns after each glyph")
    ap.add_argument("--line-gap", type=int, default=1, help="blank rows between lines")
    ap.add_argument("--name", required=True)
    ap.add_argument("--scales", type=int, nargs="+", default=[1])
    ap.add_argument("--only", help="keep only these characters (others become blank), to save flash")
    ap.add_argument("--out-dir", default=Path(__file__).parent.parent / "myfonts")
    a = ap.parse_args()
    for s in a.scales:
        convert(a.folder, a.prefix, a.offset, a.ext, a.ink, a.baseline, a.spacing, a.line_gap, a.name, s, a.out_dir, a.only)


if __name__ == "__main__":
    main()
