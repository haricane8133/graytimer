#!/usr/bin/env python3
"""
Build the DFU (update mode) screen: the GRAY TIMER wordmark and the author's
name over the Prince of Persia (1989, DOS) title art, as one 200x200 1-bit
bitmap. The top 14 rows are left white for the status line, which the sketch
prints (showUpdateMode in graytimer.ino).

Inputs, in sources/pop/: raw/title_art.png (the game's 320x200 title screen),
processed/wordmark.png (248x58 lettering, white on black), and the in-game font via
../myfonts/PrinceOfPersia2x7b.h (see glyphs_to_gfx.py).

Usage:
    python3 generate_dfu_screen.py
    -> ../dfu_screen.h defining `dfu_screen` and previews/dfu_screen.png
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

from render_watchface import GFXFont

HERE = Path(__file__).parent
SRC = HERE / "sources" / "pop"
STATUS_H = 14     # white strip for the status line
BAND_Y = 178      # black band holding the name
GAMMA = 0.6       # brightens the dark title art before dithering


def build():
    art = Image.open(SRC / "raw" / "title_art.png").convert("RGB").convert("L").crop((60, 0, 260, 200))
    art = art.point(lambda v: min(255, int(255 * (v / 255) ** GAMMA)))
    img = art.convert("1")  # Floyd-Steinberg, at final size
    d = ImageDraw.Draw(img)

    # Wordmark: shrunk to fit the width, white with a 2 px black halo, sitting on the name band
    mark = Image.open(SRC / "processed" / "wordmark.png").convert("L")
    mark = mark.resize((196, round(mark.size[1] * 196 / mark.size[0])), Image.LANCZOS).point(lambda v: 255 if v > 120 else 0)
    x, y, r = 2, BAND_Y - mark.size[1] - 3, 2
    big = Image.new("L", (mark.size[0] + 2 * r, mark.size[1] + 2 * r), 0)
    big.paste(mark, (r, r))
    img.paste(0, (x - r, y - r), big.filter(ImageFilter.MaxFilter(2 * r + 1)).convert("1"))
    img.paste(1, (x, y), mark.convert("1"))

    d.rectangle((0, BAND_Y, 199, 199), fill=0)
    font = GFXFont(str(HERE.parent / "myfonts" / "PrinceOfPersia2x7b.h"))
    name = "Hari Rajesh"
    x1, y1, w, h = font.get_text_bounds(name)
    font.render_text(name, (200 - w) // 2 - x1, BAND_Y + 4 - y1, d, color=1)

    d.rectangle((0, 0, 199, STATUS_H - 2), fill=1)
    d.line((0, STATUS_H - 1, 199, STATUS_H - 1), fill=0)
    return img


def write_header(img, path):
    px = img.load()
    data = bytearray()
    for y in range(200):
        for xb in range(0, 200, 8):
            byte = 0
            for i in range(8):
                if px[xb + i, y] == 0:  # set bit = black
                    byte |= 0x80 >> i
            data.append(byte)
    lines = ["// Generated by watchfaceutils/generate_dfu_screen.py; do not edit",
             "// 200x200, 1 bit per pixel, set bit = black",
             "const unsigned char dfu_screen[] PROGMEM = {"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    Path(path).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    img = build()
    write_header(img, HERE.parent / "dfu_screen.h")
    img.save(HERE / "previews" / "dfu_screen.png")
    print("wrote dfu_screen.h and previews/dfu_screen.png")
